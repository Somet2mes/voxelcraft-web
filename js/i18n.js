let lang = localStorage.getItem("voxelcraft_lang") || "zh";

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === "en" ? "en" : "zh";
  localStorage.setItem("voxelcraft_lang", lang);
  return lang;
}

export function toggleLang() {
  return setLang(lang === "zh" ? "en" : "zh");
}

export function t(key) {
  return DICT[lang][key] ?? DICT.en[key] ?? key;
}

export function tBlock(nameZh, nameEn) {
  return lang === "zh" ? nameZh : nameEn;
}
